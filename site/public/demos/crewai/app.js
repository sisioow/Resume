const $ = (sel) => document.querySelector(sel)
const logEl = $('#log')
const phaseEl = $('#phase')
const reportEl = $('#report')
const reportBody = $('#report-body')
const kickoffBtn = $('#kickoff')
const replayBtn = $('#replay')
const topicInput = $('#topic')
const tasksStat = $('#stat-tasks')
const msStat = $('#stat-ms')

let running = false
let startedAt = 0
let timer = null
let tasksDone = 0

function renderAgents() {
  const root = $('#agents')
  root.innerHTML = agents
    .map(
      (a) => `
    <div class="agent" id="agent-${a.id}" style="left:${a.x}%; top:${a.y}%;">
      <div class="avatar" style="background:${a.color}">${a.name.slice(0, 1)}</div>
      <h3>${a.name}</h3>
      <p>${a.role}<br />${a.goal}</p>
      <span class="badge" data-badge>Idle</span>
    </div>
  `,
    )
    .join('')

  const svg = $('#links')
  const pairs = [
    [0, 1],
    [0, 2],
    [1, 2],
  ]
  svg.innerHTML = pairs
    .map(([i, j], idx) => {
      const a = agents[i]
      const b = agents[j]
      return `<line id="link-${idx}" x1="${(a.x / 100) * 640}" y1="${(a.y / 100) * 420}" x2="${(b.x / 100) * 640}" y2="${(b.y / 100) * 420}" />`
    })
    .join('')
}

function setAgentState(id, state) {
  const el = $(`#agent-${id}`)
  if (!el) return
  el.classList.remove('active', 'done')
  if (state === 'active') el.classList.add('active')
  if (state === 'done') el.classList.add('done')
  const badge = el.querySelector('[data-badge]')
  badge.textContent = state === 'active' ? 'Working' : state === 'done' ? 'Done' : 'Idle'
}

function setLink(activeIdx) {
  ;[0, 1, 2].forEach((i) => {
    const line = $(`#link-${i}`)
    if (!line) return
    line.classList.toggle('active', i === activeIdx)
  })
}

function pushLog(message, kind = '') {
  const now = new Date()
  const t = `${String(now.getMinutes()).padStart(2, '0')}:${String(now.getSeconds()).padStart(2, '0')}`
  const li = document.createElement('li')
  if (kind) li.className = kind
  li.innerHTML = `<span class="t">${t}</span><span class="m">${message}</span>`
  logEl.prepend(li)
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms))
}

function buildReport(topic) {
  return `# ${topic}

## Executive Summary
- Crew 以 Sequential Process 完成检索 → 成稿 → 质检
- 覆盖开源 Agent 框架、MCP 工具链与落地交付路径
- 产出可直接用于内部评审的结构化 Markdown

## Key Findings
1. **编排层**：Crews 解决角色协作；Flows 解决事件驱动分支
2. **工具层**：Search / RAG / FileWriter 形成闭环
3. **质量层**：Critic + Guardrail 降低幻觉与漏项

## Recommended Next Steps
- 接入真实 Serper / Firecrawl 工具
- 用 \`crewai flow plot\` 导出可视化图
- 将报告节点接到 CI 或知识库

---
_Generated by CrewAI Mission Console (demo)_`
}

async function runCrew() {
  if (running) return
  running = true
  kickoffBtn.disabled = true
  replayBtn.disabled = true
  logEl.innerHTML = ''
  reportEl.hidden = true
  tasksDone = 0
  tasksStat.textContent = '0'
  agents.forEach((a) => setAgentState(a.id, 'idle'))
  setLink(-1)

  const topic = topicInput.value.trim() || '未命名任务'
  startedAt = performance.now()
  timer = setInterval(() => {
    msStat.textContent = `${((performance.now() - startedAt) / 1000).toFixed(1)}s`
  }, 100)

  phaseEl.textContent = 'Crew.kickoff()'
  pushLog(`创建 Crew · topic = <b>${topic}</b>`)
  await sleep(500)

  // Researcher
  phaseEl.textContent = 'Task 1 · Research'
  setAgentState('researcher', 'active')
  setLink(0)
  pushLog(`<b>Researcher</b> 接收任务：搜集「${topic}」一手材料`)
  await sleep(700)
  pushLog(`调用工具 <b>SerperDevTool</b> · query="${topic}"`, 'tool')
  await sleep(900)
  pushLog(`调用工具 <b>WebsiteSearchTool</b> · 抓取 6 篇高相关源`, 'tool')
  await sleep(800)
  pushLog(`Researcher 完成笔记 · 12 条洞察 / 8 条引用`, 'done')
  setAgentState('researcher', 'done')
  tasksDone = 1
  tasksStat.textContent = '1'
  await sleep(400)

  // Analyst
  phaseEl.textContent = 'Task 2 · Report'
  setAgentState('analyst', 'active')
  setLink(0)
  pushLog(`<b>Reporting Analyst</b> 接手上下文 · 开始结构化成稿`)
  await sleep(750)
  pushLog(`委派确认：沿用 Researcher 引用图，补充落地路径章节`)
  await sleep(850)
  pushLog(`写入草稿 <b>report.md</b> · sections=4`, 'tool')
  await sleep(700)
  pushLog(`Analyst 完成初稿`, 'done')
  setAgentState('analyst', 'done')
  tasksDone = 2
  tasksStat.textContent = '2'
  await sleep(350)

  // Critic
  phaseEl.textContent = 'Task 3 · Guardrail'
  setAgentState('critic', 'active')
  setLink(2)
  pushLog(`<b>Quality Critic</b> 启动质检 · guardrail_max_retries=2`)
  await sleep(650)
  pushLog(`检查项：事实引用 / 过度承诺 / 可执行性`)
  await sleep(800)
  pushLog(`发现 1 处表述过强 → 回写 Analyst 修正`, 'tool')
  setLink(1)
  await sleep(700)
  pushLog(`质检通过 · 风险标注 2 条`, 'done')
  setAgentState('critic', 'done')
  tasksDone = 3
  tasksStat.textContent = '3'

  phaseEl.textContent = 'Delivered'
  reportBody.textContent = buildReport(topic)
  reportEl.hidden = false
  pushLog(`Crew 完成 · 产物已落盘 <b>report.md</b>`, 'done')
  setLink(-1)

  clearInterval(timer)
  msStat.textContent = `${((performance.now() - startedAt) / 1000).toFixed(1)}s`
  running = false
  kickoffBtn.disabled = false
  replayBtn.disabled = false
}

document.querySelectorAll('.scenario').forEach((btn) => {
  btn.addEventListener('click', () => {
    document.querySelectorAll('.scenario').forEach((b) => b.classList.remove('active'))
    btn.classList.add('active')
    topicInput.value = btn.dataset.topic
  })
})

kickoffBtn.addEventListener('click', runCrew)
replayBtn.addEventListener('click', async () => {
  await runCrew()
})

renderAgents()
pushLog('控制台就绪 · 点击 Kickoff 或「自动演示」开始录屏')
